// Suffixes to strip during fuzzy matching
const SUFFIXES = [
  "-en", "-e", "-er", "-es", "-em", "-et", "-est", "-te", "-ten", "-tet", "-st", "-t", 
  "-ung", "-heit", "-keit", "-lich", "-isch", "-ig", "-nen", "-ern", "-eln", "-end", "-ens"
].map(s => s.replace('-', ''));

/**
 * Perform a fuzzy lookup for a German word.
 * 1. Exact match (case-insensitive)
 * 2. Lowercase match
 * 3. Suffix stripping
 * 4. Umlaut replacement
 * @param {string} word - The word to look up
 * @returns {Object|null} - Dictionary entry or null if not found
 */
function lookupGermanWord(word) {
  if (!word) return null;
  
  // Helper to check dictionary
  const check = (w) => {
    // Exact
    if (GERMAN_DICTIONARY[w]) return GERMAN_DICTIONARY[w];
    // Capitalized (for nouns)
    const cap = w.charAt(0).toUpperCase() + w.slice(1).toLowerCase();
    if (GERMAN_DICTIONARY[cap]) return GERMAN_DICTIONARY[cap];
    // Lowercase
    const low = w.toLowerCase();
    if (GERMAN_DICTIONARY[low]) return GERMAN_DICTIONARY[low];
    return null;
  };

  // 1 & 2: Try normal checks
  let result = check(word);
  if (result) return result;

  // 3: Try stripping common suffixes
  const lowerWord = word.toLowerCase();
  for (let suffix of SUFFIXES) {
    if (lowerWord.endsWith(suffix) && lowerWord.length > suffix.length) {
      const stripped = lowerWord.slice(0, -suffix.length);
      result = check(stripped);
      if (result) return result;
    }
  }

  // 4: Try replacing umlauts
  const replaceUmlauts = (str) => {
    return str.replace(/ä/g, 'a')
              .replace(/ö/g, 'o')
              .replace(/ü/g, 'u')
              .replace(/Ä/g, 'A')
              .replace(/Ö/g, 'O')
              .replace(/Ü/g, 'U');
  };
  
  const noUmlauts = replaceUmlauts(word);
  if (noUmlauts !== word) {
    result = check(noUmlauts);
    if (result) return result;
    
    // Also try suffixes on noUmlauts
    const lowerNoUmlauts = noUmlauts.toLowerCase();
    for (let suffix of SUFFIXES) {
      if (lowerNoUmlauts.endsWith(suffix) && lowerNoUmlauts.length > suffix.length) {
        const stripped = lowerNoUmlauts.slice(0, -suffix.length);
        result = check(stripped);
        if (result) return result;
      }
    }
  }

  return null;
}

